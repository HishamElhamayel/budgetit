/**
 * Countries, for the profile's "where are you" field.
 *
 * Names come from the runtime's own CLDR data (`Intl.DisplayNames`) rather than
 * being hand-typed, and are baked into the bundle for the same two reasons
 * currencies.ts is: Hermes ships a trimmed ICU, and a picker whose contents
 * shift with the device's ICU version is not something anyone can test.
 *
 * `currencyCode` is the one part CLDR cannot supply — Intl exposes no
 * country-to-currency mapping — so it is hand-kept, and validated at generation
 * time against {@link CURRENCIES}. It is a *suggestion*: onboarding uses it to
 * pre-select a currency the user can still change, and nothing else reads it.
 * Null where the country's currency isn't one the app can format.
 *
 * Sorted by name, which is the order the picker lists them in.
 */

