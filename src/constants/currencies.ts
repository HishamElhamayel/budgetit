const BY_CODE = new Map(CURRENCIES.map((currency) => [currency.code, currency]));

export function findCurrency(code: string): Currency | undefined {
  return BY_CODE.get(code);
}

/**
 * Decimal places for a currency, defaulting to 2 for a code this build has
 * never heard of — a stored preference outliving a CLDR update is not a reason
 * to crash a screen that only wanted to draw a number.
 */
export function currencyDigits(code: string): number {
  return BY_CODE.get(code)?.digits ?? 2;
}
