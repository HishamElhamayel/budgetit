/**
 * Every currency the platform can format, generated from the runtime's own CLDR
 * data (`Intl.supportedValuesOf('currency')`) rather than hand-listed.
 *
 * Baked into the bundle instead of read at runtime because Hermes does not
 * expose `supportedValuesOf`, and because a picker that changes its contents
 * depending on the device's ICU version is not something anyone can test.
 *
 * `digits` is how many decimal places the currency is written with — 0 for yen
 * and won, 2 for most, 3 for the Gulf dinars. It drives both display and how
 * much precision the amount keypad accepts; see lib/money.ts.
 */

